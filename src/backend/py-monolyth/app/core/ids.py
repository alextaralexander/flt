"""Идентификаторы сущностей и событий shared kernel (ADR-003, SYS-05-R7).

Первичные ключи таблиц модулей и `event_id` событий — UUID v7: время в старших битах
делает ключи монотонными (локальность B-tree индекса), а случайная часть исключает
согласование между инстансами — идентификатор создаёт любой инстанс без обращения к БД.
"""

import uuid
from uuid import UUID


def new_id() -> UUID:
    """Новый UUID v7 (RFC 9562) для первичного ключа или `event_id`.

    Returns:
        UUID версии 7; идентификаторы одного процесса строго возрастают.
    """
    return uuid.uuid7()
