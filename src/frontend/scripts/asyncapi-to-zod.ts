// Генерация zod-схем и типов сообщений WebSocket из AsyncAPI (ADR-005, 3.5;
// SYS-04): Analytics/Specs/<module>/api/asyncapi.yaml →
// src/features/<module>/ws/generated/messages.ts; общий конверт
// Analytics/Specs/_system/asyncapi-common.yaml → src/lib/ws/generated/messages.ts.
// Запуск: node scripts/asyncapi-to-zod.ts (входит в pnpm api:generate).
import fs from 'node:fs';
import path from 'node:path';

import { Parser } from '@asyncapi/parser';
import { jsonSchemaToZod } from 'json-schema-to-zod';

const FRONTEND_ROOT = path.resolve(import.meta.dirname, '..');
const SPECS_DIR = path.resolve(
  FRONTEND_ROOT,
  process.env.FLT_SPECS_DIR ?? '../../Analytics/Specs',
);

export type AsyncApiTarget = { input: string; output: string };

const HEADER = [
  '/**',
  ' * Generated by scripts/asyncapi-to-zod.ts from AsyncAPI.',
  ' * Do not edit manually: run `pnpm api:generate`.',
  ' */',
  "import { z } from 'zod';",
  '',
].join('\n');

/** Имя схемы: `llm_gateway.stream.delta` → `LlmGatewayStreamDelta`. */
export const schemaNameOf = (messageName: string): string =>
  messageName
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('');

/** Модуль TypeScript со схемами всех сообщений документа AsyncAPI. */
export const generateMessagesModule = async (
  source: string,
  sourcePath?: string,
): Promise<string> => {
  const parser = new Parser();
  // sourcePath нужен для относительных $ref на asyncapi-common.yaml (SYS-04-R33)
  const { document, diagnostics } = await parser.parse(
    source,
    sourcePath ? { source: sourcePath } : undefined,
  );
  if (!document) {
    const errors = diagnostics
      .filter((d) => d.severity === 0)
      .map((d) => `${d.path.join('.')}: ${d.message}`);
    throw new Error(`Invalid AsyncAPI document:\n${errors.join('\n')}`);
  }
  // Только сообщения WebSocket: каналы Kafka (`x-flt-transport: kafka`) фронтенду не нужны
  const seen = new Set<string>();
  const messages = document
    .channels()
    .all()
    .filter(
      (channel) =>
        channel.extensions().get('x-flt-transport')?.value() !== 'kafka',
    )
    .flatMap((channel) => channel.messages().all())
    .filter((message) => {
      const key = message.name() ?? message.id();
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .map((message) => ({
      name: message.name() ?? message.id(),
      payload: message.payload()?.json(),
    }))
    .filter(
      (message): message is { name: string; payload: object } =>
        Boolean(message.name) && typeof message.payload === 'object',
    )
    .sort((a, b) => a.name.localeCompare(b.name));

  const body = messages.map(({ name, payload }) => {
    const schemaName = `${schemaNameOf(name)}Schema`;
    const zod = jsonSchemaToZod(
      payload as Parameters<typeof jsonSchemaToZod>[0],
      {
        module: 'none',
      },
    );
    return [
      `/** Сообщение \`${name}\`. */`,
      `export const ${schemaName} = ${zod};`,
      `export type ${schemaNameOf(name)} = z.infer<typeof ${schemaName}>;`,
      '',
    ].join('\n');
  });
  return `${HEADER}\n${body.join('\n')}`;
};

/** Контракты AsyncAPI модулей и общий контракт; пустой список — допустимое состояние. */
export const listAsyncApiTargets = (
  specsDir: string = SPECS_DIR,
): AsyncApiTarget[] => {
  if (!fs.existsSync(specsDir)) return [];
  const targets: AsyncApiTarget[] = [];
  const common = path.join(specsDir, '_system/asyncapi-common.yaml');
  if (fs.existsSync(common)) {
    targets.push({
      input: common,
      output: path.join(FRONTEND_ROOT, 'src/lib/ws/generated/messages.ts'),
    });
  }
  for (const entry of fs.readdirSync(specsDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || entry.name.startsWith('_')) continue;
    const input = path.join(specsDir, entry.name, 'api/asyncapi.yaml');
    if (!fs.existsSync(input)) continue;
    targets.push({
      input,
      output: path.join(
        FRONTEND_ROOT,
        `src/features/${entry.name.replaceAll('_', '-')}/ws/generated/messages.ts`,
      ),
    });
  }
  return targets.sort((a, b) => a.output.localeCompare(b.output));
};

const main = async () => {
  for (const target of listAsyncApiTargets()) {
    const code = await generateMessagesModule(
      fs.readFileSync(target.input, 'utf8'),
      target.input,
    );
    fs.mkdirSync(path.dirname(target.output), { recursive: true });
    fs.writeFileSync(target.output, code);
    console.log(
      `asyncapi-to-zod: ${path.relative(FRONTEND_ROOT, target.output)}`,
    );
  }
};

if (import.meta.main) {
  await main();
}
